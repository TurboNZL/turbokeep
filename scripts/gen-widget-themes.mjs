#!/usr/bin/env node
// Writes apps/android/app/src/main/kotlin/app/turbokeep/android/WidgetThemes.kt from the engine's own palettes and UI styles (TurboNZL/turboengine, themes/).
// A widget cannot run the theme engine, so the palettes are worked out HERE with the engine's own buildPalette/tokens and copied into Kotlin as plain colours.
// Usage: node scripts/gen-widget-themes.mjs /path/to/turboengine
import { readdirSync, readFileSync, existsSync, writeFileSync } from 'node:fs';
import { join, resolve, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const engine = resolve(process.argv[2] ?? '../turbonzl/turboengine');
const themes = join(engine, 'themes');
const m = await import(pathToFileURL(join(themes, 'dist/engine.js')).href);
const sha = (process.env.ENGINE_REF ?? '').slice(0, 7);

const specs = [];
for (const d of readdirSync(join(themes, 'themes')).sort()) {
  const f = join(themes, 'themes', d, 'theme.json');
  if (existsSync(f)) specs.push(...(JSON.parse(readFileSync(f, 'utf8')).palettes ?? []));
}
// the palettes a phone widget offers: the apps' own pairs, the colour palettes, and the games/apps looks. (The device looks, Windows/macOS/GNOME..., are for matching a device.)
const groups = new Set(['own', 'colour', 'inspired']);
const trip = (t) => { const [h, s, l] = t.split(/[\s%]+/).filter(Boolean).map(Number); const a = (s / 100) * Math.min(l / 100, 1 - l / 100); const f = (n) => { const k = (n + h / 30) % 12; const c = l / 100 - a * Math.max(-1, Math.min(k - 3, 9 - k, 1)); return Math.round(255 * c).toString(16).padStart(2, '0'); }; return `0xFF${(f(0) + f(8) + f(4)).toUpperCase()}.toInt()`; };
const q = (s) => JSON.stringify(s);
const rows = [];
for (const s of specs.sort((a, b) => (a.order ?? 99) - (b.order ?? 99))) {
  if (!groups.has(s.group ?? 'colour')) continue;
  const p = m.buildPalette(s);
  if (p.own) continue; // default/classic/light are drawn by CSS, not worked out
  const t = m.tokens(p);
  rows.push(`        P(${q(s.id)}, ${q(s.label)}, ${p.dark}, ${['bg', 'surface', 'line', 'fg', 'muted', 'accent', 'accent-fg', 'bad'].map((k) => trip(t[k])).join(', ')}),`);
}

const styles = JSON.parse(readFileSync(join(themes, 'dist/themes.json'), 'utf8')).styles;
/** the nearest font Android has built in: a widget can only use the system's families (TypefaceSpan names), not the web fonts */
const family = (f) => /VT323|Press Start|Mono/i.test(f) ? 'monospace' : /Burbank|Condensed|Anton/i.test(f) ? 'sans-serif-condensed' : /Light/i.test(f) ? 'sans-serif-light'
  : /Nunito|Outfit|Figtree|Ubuntu|Lucida|Heading Now/i.test(f) ? 'sans-serif-medium' : 'sans-serif';
const srows = styles.map((s) => `        S(${q(s.id)}, ${q(s.label)}, ${q(s.font)}, ${q(family(s.font))}),`);
// the fonts the widget settings offer (one per distinct look; the rest still map when the app's own look is followed)
const offered = ['default', 'material', 'oneui', 'spotify', 'zune', 'cyber', 'pipboy', 'fortnite2'];

const out = `package app.turbokeep.android

/**
 * GENERATED by scripts/gen-widget-themes.mjs from TurboNZL/turboengine${sha ? ` @ ${sha}` : ''} (themes/): do not edit by hand.
 * The engine's palettes (worked out with its own buildPalette/tokens) and UI styles, as plain values a widget can use.
 * Fonts: a widget can only use the families Android ships, so each style's web font is mapped to the nearest one.
 */
object WidgetThemes {
    class P(val id: String, val label: String, val dark: Boolean, val bg: Int, val surface: Int, val line: Int, val fg: Int, val muted: Int, val accent: Int, val accentFg: Int, val bad: Int)
    class S(val id: String, val label: String, val font: String, val family: String)

    val PALETTES = listOf(
${rows.join('\n')}
    )

    val STYLES = listOf(
${srows.join('\n')}
    )

    /** the styles the widget settings list (the engine's UI styles whose fonts look different from each other) */
    val OFFERED_STYLES = listOf(${offered.map(q).join(', ')})

    fun palette(id: String): P? = PALETTES.firstOrNull { it.id == id }
    fun style(id: String): S? = STYLES.firstOrNull { it.id == id }
}
`;
writeFileSync(join(dirname(fileURLToPath(import.meta.url)), '../apps/android/app/src/main/kotlin/app/turbokeep/android/WidgetThemes.kt'), out);
console.log(`${rows.length} palettes, ${srows.length} styles`);
